#!/usr/bin/env bash
# Builds the OrbitWatch Zarf package: dist/zarf-package-orbitwatch-<arch>-0.2.0.tar.zst
#
# Run on a machine WITH internet that can pull the image.
#
# Usage:
#   IMAGE_REF=registry.gitlab.com/you/orbitwatch:abc123 ./scripts/zarf-package.sh
#   TLE_FILE=data/current.tle IMAGE_REF=... ./scripts/zarf-package.sh   # ship real orbit data
#   SIGNING_KEY=cosign.key COSIGN_PASSWORD=... IMAGE_REF=... ./scripts/zarf-package.sh
#
# Deploy on the air-gapped cluster (after `zarf init` there):
#   zarf package deploy zarf-package-orbitwatch-amd64-0.2.0.tar.zst --confirm
#   # if the package was signed:
#   zarf package deploy zarf-package-orbitwatch-amd64-0.2.0.tar.zst --key cosign.pub --confirm
set -euo pipefail

: "${IMAGE_REF:?Set IMAGE_REF, e.g. registry.gitlab.com/you/orbitwatch:abc123}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VALUES="$ROOT/zarf/values.generated.yaml"

# Split "registry/path/name:tag" into the chart's image values
REF_NO_TAG="${IMAGE_REF%:*}"
TAG="${IMAGE_REF##*:}"
REGISTRY="${REF_NO_TAG%%/*}"
REPOSITORY="${REF_NO_TAG#*/}"

echo "==> Writing chart values for $REGISTRY/$REPOSITORY:$TAG"
{
  echo "# Generated by scripts/zarf-package.sh. Do not edit by hand."
  echo "image:"
  echo "  registry: \"$REGISTRY\""
  echo "  repository: \"$REPOSITORY\""
  echo "  tag: \"$TAG\""
  echo "  pullPolicy: IfNotPresent"
  if [[ -n "${TLE_FILE:-}" ]]; then
    echo "tle:"
    echo "  data: |"
    sed 's/^/    /' "$TLE_FILE"
  fi
} > "$VALUES"

SIGN_ARGS=()
if [[ -n "${SIGNING_KEY:-}" ]]; then
  echo "==> Package will be signed with $SIGNING_KEY"
  SIGN_ARGS=(--signing-key "$SIGNING_KEY" --signing-key-pass "${COSIGN_PASSWORD:-}")
fi

mkdir -p "$ROOT/dist"
zarf package create "$ROOT/zarf" --confirm \
  --set "IMAGE_REF=$IMAGE_REF" \
  --output "$ROOT/dist" \
  "${SIGN_ARGS[@]}"

echo "==> Done:"
ls -lh "$ROOT"/dist/zarf-package-orbitwatch-*.tar.zst
